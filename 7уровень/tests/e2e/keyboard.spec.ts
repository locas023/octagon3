import { test,expect } from '@playwright/test'
test('keyboard login, mobile menu arrows/Escape and modal focus return',async({page})=>{
 await page.setViewportSize({width:360,height:800})
 await page.goto('/login');await page.waitForFunction(()=>document.documentElement.dataset.appReady==='true')
 await page.getByLabel('Электронная почта').focus()
 await page.keyboard.type('admin@workflow.demo');await page.keyboard.press('Tab');await page.keyboard.type('WorkflowDemo2026!');await page.keyboard.press('Tab');await page.keyboard.press('Enter')
 await expect(page).toHaveURL(/dashboard/)
 const burger=page.getByRole('button',{name:'Открыть меню',exact:true})
 await burger.focus();await page.keyboard.press('Enter')
 const menu=page.getByRole('navigation',{name:'Мобильная навигация'})
 await expect(menu).toBeVisible();await page.keyboard.press('ArrowDown')
 await expect(menu.getByRole('link',{name:'Заявки',exact:true})).toBeFocused()
 await page.keyboard.press('Escape');await expect(menu).toBeHidden();await expect(burger).toBeFocused()
 const created=await page.request.post('/api/admin/categories',{data:{name:`Keyboard ${crypto.randomUUID()}`}})
 expect(created.status()).toBe(201);const item=await created.json()
 await page.goto('/admin/categories');await page.waitForFunction(()=>document.documentElement.dataset.appReady==='true')
 const remove=page.getByRole('button',{name:`Удалить ${item.name}`,exact:true})
 await remove.focus();await page.keyboard.press('Enter')
 const dialog=page.getByRole('dialog',{name:'Удалить запись?'})
 await expect(dialog).toBeVisible()
 for(let i=0;i<8;i++)await page.keyboard.press('Tab')
 expect(await dialog.evaluate(element=>element.contains(document.activeElement))).toBe(true)
 await page.keyboard.press('Escape');await expect(dialog).toBeHidden();await expect(remove).toBeFocused()
 await page.request.delete(`/api/admin/categories/${item.id}`)
})
